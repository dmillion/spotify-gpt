(() => {
  let updating = false;
  let runtime = {ollama_mode:'unknown', ollama_model:''};

  const compact = value => {
    const number = Number(value);
    if (!Number.isFinite(number)) return '—';
    if (number >= 1_000_000) return `${(number / 1_000_000).toFixed(number >= 10_000_000 ? 0 : 1)}M`;
    if (number >= 1_000) return `${(number / 1_000).toFixed(1)}K`;
    return number.toLocaleString();
  };

  function installStyles() {
    if (document.querySelector('#usage-display-styles')) return;
    const style = document.createElement('style');
    style.id = 'usage-display-styles';
    style.textContent = `
      .usage-explainer {
        margin:8px 0 0;
        color:var(--muted);
        font:11px/1.55 'DM Mono',monospace;
      }
      .usage-mode {
        display:inline-block;
        margin-top:8px;
        padding:3px 6px;
        border:1px solid var(--line);
        color:var(--acid);
        font:10px/1.4 'DM Mono',monospace;
        text-transform:uppercase;
        letter-spacing:.06em;
      }
      .usage-value {
        white-space:nowrap;
        overflow-wrap:normal !important;
      }
      .usage-share {
        display:block;
        margin-top:5px;
        color:var(--muted);
        font:10px/1.4 'DM Mono',monospace;
      }
      #usage-total { font-size:38px !important; letter-spacing:-.04em !important; }
      .usage-grid { gap:20px 14px !important; }
    `;
    document.head.appendChild(style);
  }

  function relabel() {
    const usage = document.querySelector('.usage');
    if (!usage) return;

    const local = runtime.ollama_mode === 'local';
    const model = String(runtime.ollama_model || '').trim();
    const title = document.querySelector('#usage-title');
    if (title) title.textContent = local ? 'Local model workload' : 'Ollama cloud usage';

    const labels = local
      ? [
          ['#usage-total', 'All-time workload'],
          ['#usage-today', 'Today (UTC)'],
          ['#usage-input', 'Context processed'],
          ['#usage-output', 'Generated locally'],
        ]
      : [
          ['#usage-total', 'All-time tokens'],
          ['#usage-today', 'Today (UTC)'],
          ['#usage-input', 'Sent to cloud model'],
          ['#usage-output', 'Generated by model'],
        ];

    labels.forEach(([selector, text]) => {
      const value = document.querySelector(selector);
      const label = value?.parentElement?.querySelector('.meta');
      if (label) label.textContent = text;
    });

    let explainer = usage.querySelector('.usage-explainer');
    if (!explainer) {
      explainer = document.createElement('p');
      explainer.className = 'usage-explainer';
      title?.insertAdjacentElement('afterend', explainer);
    }
    explainer.textContent = local
      ? `Token workload processed on this Mac${model ? ` by ${model}` : ''}. Higher counts mainly mean more local compute, memory pressure, and inference time—not API charges or account quota.`
      : `Tokens processed through Ollama Cloud${model ? ` by ${model}` : ''}. This is measured Tune Raider traffic; cloud tokens may matter for account limits or billing depending on your Ollama plan.`;

    let badge = usage.querySelector('.usage-mode');
    if (!badge) {
      badge = document.createElement('span');
      badge.className = 'usage-mode';
      explainer.insertAdjacentElement('afterend', badge);
    }
    badge.textContent = local ? 'Local inference' : runtime.ollama_mode === 'cloud' ? 'Cloud inference' : 'Ollama';
  }

  async function loadRuntime() {
    try {
      const response = await fetch('/api/runtime', {cache:'no-store'});
      if (!response.ok) return;
      runtime = await response.json();
      relabel();
    } catch (_) {
      // Keep the generic labels if runtime mode cannot be determined.
    }
  }

  async function refresh() {
    try {
      const response = await fetch('/api/usage', {cache:'no-store'});
      if (!response.ok) return;
      const data = await response.json();
      const total = Number(data.total_tokens) || 0;
      const today = Number(data.today_tokens) || 0;
      const input = Number(data.input_tokens) || 0;
      const output = Number(data.output_tokens) || 0;
      const splitTotal = input + output;
      const local = runtime.ollama_mode === 'local';

      updating = true;
      const values = {
        '#usage-total': [total, local ? 'all-time locally processed tokens' : 'all-time recorded cloud tokens'],
        '#usage-today': [today, 'tokens recorded today (UTC)'],
        '#usage-input': [input, local ? 'tokens processed locally as prompts, instructions, schemas and candidate context' : 'tokens sent to the cloud model as prompts, instructions, schemas and candidate context'],
        '#usage-output': [output, local ? 'tokens generated by the local model' : 'tokens generated by the cloud model'],
      };
      Object.entries(values).forEach(([selector, [value, description]]) => {
        const node = document.querySelector(selector);
        if (!node) return;
        node.textContent = compact(value);
        node.title = `${value.toLocaleString()} ${description}`;
      });

      const inputNode = document.querySelector('#usage-input');
      const outputNode = document.querySelector('#usage-output');
      const addShare = (node, value) => {
        if (!node) return;
        let share = node.parentElement.querySelector('.usage-share');
        if (!share) {
          share = document.createElement('span');
          share.className = 'usage-share';
          node.insertAdjacentElement('afterend', share);
        }
        share.textContent = splitTotal ? `${Math.round(value / splitTotal * 100)}% of token workload` : '—';
      };
      addShare(inputNode, input);
      addShare(outputNode, output);

      const inputBar = document.querySelector('#usage-input-bar');
      const outputBar = document.querySelector('#usage-output-bar');
      if (inputBar) inputBar.style.width = `${splitTotal ? input / splitTotal * 100 : 0}%`;
      if (outputBar) outputBar.style.width = `${splitTotal ? output / splitTotal * 100 : 0}%`;
      updating = false;
    } catch (_) {
      updating = false;
    }
  }

  async function install() {
    installStyles();
    relabel();
    await loadRuntime();
    await refresh();
    setInterval(() => { if (!document.hidden) refresh(); }, 10000);

    const usage = document.querySelector('.usage');
    if (usage) {
      new MutationObserver(() => {
        if (updating) return;
        relabel();
      }).observe(usage, {childList:true, subtree:true});
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', install);
  else install();
})();
